"""Emit manuscript/numbers.tex: every number the paper cites, as a LaTeX macro.

The manuscript never contains a literal measurement. It writes \\CpdpmRatioOne
and the like, and this script regenerates those macros from the pinned result
files, so the text cannot drift from the evidence.

Run: python -m paper.manuscript_numbers
"""

from __future__ import annotations

import json
from pathlib import Path

ROOT = Path(__file__).resolve().parents[1]
OUT = ROOT / "manuscript" / "numbers.tex"


def _macro(name: str, value: object) -> str:
    return f"\\newcommand{{\\{name}}}{{{value}}}"


def main() -> None:
    bench = json.loads((ROOT / "paper/evaluation/results/benchmark.json").read_text())
    rows = {(r["scheme"], r["op"], r["n"]): r for r in bench["rows"]}
    pre = json.loads((ROOT / "paper/analysis/results/pre_transform.json").read_text())
    fair = json.loads((ROOT / "paper/analysis/results/fair_benchmark.json").read_text())
    swap = json.loads((ROOT / "paper/evaluation/results/record_swap.json").read_text())
    overhead = json.loads((ROOT / "paper/construction/results/overhead.json").read_text())
    x86_path = ROOT / "paper/evaluation/results/benchmark_x86_64.json"
    x86 = json.loads(x86_path.read_text()) if x86_path.exists() else None

    words = {1: "One", 10: "Ten", 100: "Hundred", 1000: "Thousand"}
    lines = ["% Generated by paper/manuscript_numbers.py. Do not edit."]
    for n, w in words.items():
        g = rows[("aes-gcm", "encrypt", n)]
        c = rows[("cpdpm-gcm", "encrypt", n)]
        lines += [
            _macro(f"Bytes{w}", f"{g['bytes']:,}"),
            _macro(f"GcmUs{w}", f"{g['median_us']:.1f}"),
            _macro(f"CpdpmUs{w}", f"{c['median_us']:.1f}"),
            _macro(f"CpdpmRatio{w}", f"{c['ratio_to_aes_gcm']:.2f}"),
            _macro(f"FernetRatio{w}", f"{rows[('fernet', 'encrypt', n)]['ratio_to_aes_gcm']:.2f}"),
            _macro(f"TinkRatio{w}", f"{rows[('tink', 'encrypt', n)]['ratio_to_aes_gcm']:.2f}"),
            _macro(
                f"XchachaRatio{w}",
                f"{rows[('cpdpm-xchacha', 'encrypt', n)]['ratio_to_aes_gcm']:.0f}",
            ),
        ]
    fixed = (
        rows[("cpdpm-gcm", "encrypt", 1)]["median_us"]
        - rows[("aes-gcm", "encrypt", 1)]["median_us"]
    )
    lines += [
        _macro("CpdpmFixedUs", f"{fixed:.0f}"),
        _macro("FhirFieldsEncUs", f"{rows[('cpdpm-fhir-fields', 'encrypt', 1)]['median_us']:.0f}"),
        _macro("FhirFieldsDecUs", f"{rows[('cpdpm-fhir-fields', 'decrypt', 1)]['median_us']:.0f}"),
        _macro("BenchPlatform", bench["_meta"]["platform"].replace("_", "\\_")),
        _macro("BenchPython", bench["_meta"]["python"].split()[0]),
        _macro("Keyspace", f"{pre['effective_keyspace']['distinct_transforms']:,}"),
        _macro("KeyspaceLog", f"{pre['effective_keyspace']['log2_distinct']:.0f}"),
        _macro(
            "DiffusionMean",
            f"{pre['diffusion']['mean_output_bytes_changed_per_input_byte_flip']:.1f}",
        ),
        _macro("DiffusionTrials", f"{pre['diffusion']['trials']:,}"),
    ]
    for s in fair["sizes_bytes"]:
        r = fair["per_size"][str(s)]
        tag = {1024: "OneK", 8192: "EightK", 65536: "SixtyFourK", 524288: "FiveTwelveK"}[s]
        lines += [
            _macro(f"PreEnc{tag}", f"{r['ratio_encrypt']:.2f}"),
            _macro(f"PreDec{tag}", f"{r['ratio_decrypt']:.2f}"),
            _macro(f"PreLoop{tag}", f"{r['component_transform_loop']['median_ms']:.1f}"),
        ]
    lines.append(
        _macro("PbkdfMs", f"{fair['per_size']['1024']['component_pbkdf2']['median_ms']:.0f}")
    )

    def cell(scheme: str, attack: str) -> str:
        return swap["matrix"][scheme][attack]

    schemes = {
        "Cbc": "AES-256-CBC + HMAC, one shared key",
        "Gcm": "AES-256-GCM, key per tenant, no AAD",
        "Cpdpm": "CPDPM (this work)",
    }
    for key, name in schemes.items():
        for attack, short in (
            ("patient_swap", "Patient"),
            ("tenant_move", "Tenant"),
            ("field_move", "Field"),
            ("stale_replay_after_retirement", "Replay"),
        ):
            lines.append(_macro(f"Swap{key}{short}", cell(name, attack)))
    lines.append(_macro("SwapFhir", swap["fhir_layer"]["patient_swap"]["outcome"]))

    if x86:
        xrows = {(r["scheme"], r["op"], r["n"]): r for r in x86["rows"]}
        for n, w in words.items():
            lines += [
                _macro(
                    f"XCpdpmRatio{w}",
                    f"{xrows[('cpdpm-gcm', 'encrypt', n)]['ratio_to_aes_gcm']:.2f}",
                ),
                _macro(
                    f"XXchachaRatio{w}",
                    f"{xrows[('cpdpm-xchacha', 'encrypt', n)]['ratio_to_aes_gcm']:.0f}",
                ),
                _macro(
                    f"XFernetRatio{w}", f"{xrows[('fernet', 'encrypt', n)]['ratio_to_aes_gcm']:.0f}"
                ),
            ]
        xfixed = (
            xrows[("cpdpm-gcm", "encrypt", 1)]["median_us"]
            - xrows[("aes-gcm", "encrypt", 1)]["median_us"]
        )
        lines.append(_macro("XCpdpmFixedUs", f"{xfixed:.0f}"))
        cpu = "AMD EPYC 9V45"
        lines.append(_macro("XCpu", cpu))

    o = {r["plaintext_bytes"]: r for r in overhead}
    lines += [
        _macro("OverheadGcm", o[726]["gcm_blob_overhead"]),
        _macro("OverheadXchacha", o[726]["xchacha_blob_overhead"]),
        _macro("OverheadStreamLarge", o[669830]["gcm_stream_64k_overhead"]),
    ]
    OUT.parent.mkdir(exist_ok=True)
    OUT.write_text("\n".join(lines) + "\n")
    print(f"wrote {OUT.relative_to(ROOT)} ({len(lines) - 1} macros)")


if __name__ == "__main__":
    main()
